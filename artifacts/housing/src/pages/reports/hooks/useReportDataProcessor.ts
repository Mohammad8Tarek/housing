// Row builders live in @workspace/report-rows so the API can build the same
// rows for server-side pagination.
import { buildReportRows } from "@workspace/report-rows";

export function useReportDataProcessor({
  ar = true,
  activeTab,
  filterBuilding,
  filterFloor,
  filterStatus,
  filterCategory,
  inventoryViewMode = "summary",
  filterDepartment,
  filterGender,
  filterNationality,
  filterRoomType,
  filterEmploymentType,
  waterSortMode = "room",
  search,
  dateFrom,
  dateTo,
  buildings,
  floors,
  rooms,
  profiles,
  assignments,
  reservations,
  maintenance,
  hostings,
  equipmentInventory = [],
  gateLogs = [],
  vacations = [],
  buildingMap,
  floorMap,
  roomMap,
  empMap,
  settings = {},
}: any) {
  const currentData = (): any[] =>
    buildReportRows(
      {
        ar,
        activeTab,
        filterBuilding,
        filterFloor,
        filterStatus,
        filterCategory,
        inventoryViewMode,
        filterDepartment,
        filterGender,
        filterNationality,
        filterRoomType,
        filterEmploymentType,
        waterSortMode,
        search,
        dateFrom,
        dateTo,
      },
      {
        buildings,
        floors,
        rooms,
        profiles,
        assignments,
        reservations,
        maintenance,
        hostings,
        equipmentInventory,
        gateLogs,
        vacations,
        settings,
      },
      { buildingMap, floorMap, roomMap, empMap },
    );

  return { currentData };
}
